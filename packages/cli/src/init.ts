import { mkdir, readFile, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import {
  type ContainerRuntime,
  type HarnessProjectConfig,
  mergeHarnessProjectConfig,
} from "@pi-harness/shared";
import type { ExecFile } from "./exec.js";

export type PlannedFile = {
  readonly path: string;
  readonly content: string;
};

export type InitPlan =
  | {
      readonly ok: true;
      readonly config: HarnessProjectConfig;
      readonly files: ReadonlyArray<PlannedFile>;
      readonly warnings: ReadonlyArray<string>;
    }
  | {
      readonly ok: false;
      readonly error: "not_git_repo" | "no_container_runtime";
      readonly message: string;
    };

export async function createInitPlan(opts: {
  readonly cwd: string;
  readonly env: Readonly<Record<string, string | undefined>>;
  readonly execFile: ExecFile;
}): Promise<InitPlan> {
  const root = await detectGitRoot(opts.cwd, opts.execFile);
  if (!root) {
    return {
      ok: false,
      error: "not_git_repo",
      message: "pi-harness init must be run inside an existing git repository.",
    };
  }

  const runtime = await detectContainerRuntime(opts.execFile);
  if (!runtime) {
    return {
      ok: false,
      error: "no_container_runtime",
      message: "Neither podman nor docker is available on PATH.",
    };
  }

  const baseBranch = await detectBaseBranch(root, opts.execFile);
  const config = mergeHarnessProjectConfig({
    repoRoot: root,
    baseBranch,
    containerRuntime: runtime,
  });
  const files = await plannedFiles(root, config);
  return { ok: true, config, files, warnings: [] };
}

export async function applyInitPlan(root: string, plan: Extract<InitPlan, { ok: true }>): Promise<void> {
  for (const file of plan.files) {
    const fullPath = join(root, file.path);
    await mkdir(dirname(fullPath), { recursive: true });
    await writeFile(fullPath, file.content);
  }
}

