async function plannedFiles(root: string, config: HarnessProjectConfig): Promise<ReadonlyArray<PlannedFile>> {
  return [
    { path: "harness.config.ts", content: renderHarnessConfig(config) },
    { path: ".env.harness.example", content: renderEnvHarnessExample(config) },
    { path: ".harness/runtime/compose.yml", content: renderComposeFile(config) },
    { path: ".harness/README.md", content: renderHarnessReadme(config) },
    { path: ".gitignore", content: await renderGitignore(root) },
    ...(await renderPackageJson(root)),
  ];
}

async function renderGitignore(root: string): Promise<string> {
  const path = join(root, ".gitignore");
  const current = existsSync(path) ? await readFile(path, "utf8") : "";
  if (current.split(/\r?\n/).includes(".harness/")) return current;
  const separator = current.length > 0 && !current.endsWith("\n") ? "\n" : "";
  return `${current}${separator}.harness/\n`;
}

async function renderPackageJson(root: string): Promise<ReadonlyArray<PlannedFile>> {
  const path = join(root, "package.json");
  if (!existsSync(path)) return [];
  const parsed = parseJsonObject(await readFile(path, "utf8"));
  if (!parsed) return [];
  const scripts = parseJsonObject(parsed["scripts"]);
  const next = {
    ...parsed,
    scripts: {
      ...scripts,
      "pi-harness": "pi-harness",
    },
  };
  return [{ path: "package.json", content: `${JSON.stringify(next, null, 2)}\n` }];
}

function parseJsonObject(value: unknown): Record<string, unknown> | null {
  if (typeof value === "string") {
    try {
      return parseJsonObject(JSON.parse(value));
    } catch {
      return null;
    }
  }
  if (typeof value !== "object" || value === null || Array.isArray(value)) return null;
  return Object.fromEntries(Object.entries(value));
}

async function detectGitRoot(cwd: string, execFile: ExecFile): Promise<string | null> {
  const result = await execFile("git", ["rev-parse", "--show-toplevel"], { cwd });
  return result.ok ? result.stdout.trim() : null;
}

async function detectBaseBranch(root: string, execFile: ExecFile): Promise<string> {
  const current = await execFile("git", ["branch", "--show-current"], { cwd: root });
  if (current.ok && current.stdout.trim()) return current.stdout.trim();
  const symbolic = await execFile("git", ["symbolic-ref", "refs/remotes/origin/HEAD"], { cwd: root });
  if (!symbolic.ok) return "main";
  return symbolic.stdout.trim().replace(/^refs\/remotes\/origin\//, "") || "main";
}

async function detectContainerRuntime(execFile: ExecFile): Promise<ContainerRuntime | null> {
  const podman = await execFile("podman", ["--version"]);
  if (podman.ok) return "podman";
  const docker = await execFile("docker", ["--version"]);
  if (docker.ok) return "docker";
  return null;
}
